export type StudioCopyKey = keyof typeof en;

const tables: Record<Locale, Record<StudioCopyKey, string>> = { en, th };

export function hasStudioCopy(key: string): key is StudioCopyKey {
  return key in en;
}

export function studioCopy(locale: Locale, key: StudioCopyKey, params?: TranslationParams): string {
  const template = tables[locale][key] ?? en[key] ?? key;
  return params ? template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`)) : template;
}

export function useStudioCopy() {
  const { locale } = useLocale();
  const c = useCallback((key: StudioCopyKey, params?: TranslationParams) => studioCopy(locale, key, params), [locale]);
  return { c, locale };
}
